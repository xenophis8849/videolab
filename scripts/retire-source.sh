#!/usr/bin/env bash
# 原视频处理 —— 把源文件移入回收目录，而不是删除。
#
#   retire-source.sh <源文件> <已验证的产出> [回收目录]
#
# **删除的前置条件是产出验证已通过。** 调用方必须先跑 verify_output，
# 这里再独立复核一次「产出存在且非空、比源新」，两道都过才动源文件。
# 没有验证就删原片，一次静默的编码失败等于毁素材。
#
# 为什么是移动而不是删除：可逆。回收目录满了由使用者自己清 —— 存储空间管理
# 不属于本工具的职责，所以这里不做容量检查也不发警告。
#
# 默认策略（由调用方按模式传入，本脚本不猜）：
#   仅转码   -> 默认退休原片（成品更小，符合省空间的初衷）
#   修复+转码 -> 默认保留原片（成品像素数是源的 4 倍、通常更大，
#                删掉不省空间却永久失去原始素材）
set -uo pipefail

SRC=${1:?用法: retire-source.sh <源文件> <产出> [回收目录]}
OUT=${2:?}
TRASH=${3:-$HOME/videolab/trash}

[ -f "$SRC" ] || { echo "源文件不存在: $SRC" >&2; exit 1; }

# 独立复核，不信任调用方说的「已验证」
[ -s "$OUT" ] || { echo "拒绝：产出不存在或为空，不动源文件" >&2; exit 1; }
[ "$OUT" -nt "$SRC" ] || { echo "拒绝：产出不比源文件新，可能是上一次的残留" >&2; exit 1; }

# 回收目录里保留原始路径结构，避免不同目录的同名文件互相覆盖，
# 也方便你日后原样还原。
rel=${SRC#/}
dest="$TRASH/$(date +%Y%m%d)/$rel"
mkdir -p "$(dirname "$dest")" || exit 1

# 跨设备时 mv 会退化成拷贝+删除；先拷后删并校验，避免中途失败两头不着。
if mv "$SRC" "$dest" 2>/dev/null; then
    :
else
    cp -p "$SRC" "$dest" || { echo "拷贝到回收目录失败，源文件未动" >&2; exit 1; }
    [ "$(stat -c%s "$SRC")" = "$(stat -c%s "$dest")" ] || {
        echo "拷贝后大小不符，源文件未动" >&2; rm -f "$dest"; exit 1; }
    rm -f "$SRC"
fi

echo "原片已退休: $dest"
